/**
 * Страна, из которой идут тесты. Сайт определяет её по IP и за пределами Казахстана показывает
 * урезанный каталог: нет разделов «ТВ», «Кино на ТВ», «Спорт», «Новинки», нет баннера выбора языка
 * (язык по умолчанию английский), часть фильмов и мультфильмов недоступна.
 * - kz — пользователь из Казахстана (по умолчанию, локальный запуск);
 * - intl — зарубежный пользователь (GitHub Actions: серверы в США). Задаётся переменной REGION=intl.
 */
export type Region = "kz" | "intl";

export const REGION: Region = process.env.REGION === "intl" ? "intl" : "kz";

/** Тег проверок только для пользователя из Казахстана (в тестах — строкой: { tag: "@kz-only" }); при REGION=intl они не запускаются */
export const KZ_ONLY = "@kz-only";

/** Элемент доступен в текущем регионе (kzOnly — только в Казахстане) */
export function inRegion(item: { kzOnly?: boolean }): boolean {
  return !item.kzOnly || REGION === "kz";
}
